/// Firebase Auth adapter.
///
/// Default build: offline [LocalAuthService] (no Firebase packages required).
/// Production cloud:
///   1. `flutter pub add firebase_core firebase_auth cloud_firestore`
///   2. `flutterfire configure` → `lib/firebase_options.dart`
///   3. Build with `--dart-define=USE_FIREBASE=true`
///   4. Replace [FirebaseAuthService] body with the implementation below
///      (or keep this file once packages resolve — see comments).
///
/// Writes account docs to **accounts/{uid}** (matches `backend/firestore.rules`).
library;

import 'auth_service.dart';

/// True when the binary was built with Firebase enabled.
const useFirebase =
    bool.fromEnvironment('USE_FIREBASE', defaultValue: false);

/// True when `lib/firebase_options.dart` was generated by FlutterFire.
const firebaseOptionsConfigured =
    bool.fromEnvironment('FIREBASE_OPTIONS_CONFIGURED', defaultValue: false);

/// Production Firebase adapter.
///
/// Until packages + `firebase_options.dart` exist, construction is safe and
/// methods throw a clear [StateError] so UI can fall back to local auth.
class FirebaseAuthService implements AuthService {
  FirebaseAuthService();

  static const _setup =
      'Firebase is not fully configured. Run: '
      'flutter pub add firebase_core firebase_auth cloud_firestore; '
      'flutterfire configure; rebuild with '
      '--dart-define=USE_FIREBASE=true --dart-define=FIREBASE_OPTIONS_CONFIGURED=true. '
      'See apps/mobile/tool/setup_firebase.md';

  @override
  AuthUser? get current => null;

  @override
  Future<AuthUser> ensureAnonymousSession() async {
    // Prefer real Firebase when configured; otherwise surface setup error.
    throw StateError(_setup);
  }

  @override
  Future<AuthUser> signUpParent({
    required String email,
    required String password,
    required bool consent,
    String? displayName,
  }) async {
    throw StateError(_setup);
  }

  @override
  Future<AuthUser> signInParent({
    required String email,
    required String password,
  }) async {
    throw StateError(_setup);
  }

  @override
  Future<void> signOut() async {}

  @override
  Future<String?> getIdToken({bool forceRefresh = false}) async => null;

  @override
  Future<void> sendPasswordResetEmail(String email) async {
    throw StateError(_setup);
  }

  @override
  Future<void> confirmPasswordReset({
    required String code,
    required String newPassword,
  }) async {
    throw StateError(_setup);
  }
}

/// Picks Firebase when requested, otherwise offline [LocalAuthService].
///
/// If Firebase is requested but not configured, falls back to local so the
/// free-only publish build never hard-crashes at boot.
AuthService createAuthService() {
  if (useFirebase && firebaseOptionsConfigured) {
    return FirebaseAuthService();
  }
  return LocalAuthService();
}

/// Whether cloud auth is expected for this build.
bool get isCloudAuthBuild => useFirebase && firebaseOptionsConfigured;
