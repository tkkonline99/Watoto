/// Firebase Auth + Firestore account adapter.
///
/// Default offline build: [createAuthService] returns [LocalAuthService] when
/// [isFirebaseInitialized] is false.
/// Once `flutterfire configure` has populated `lib/firebase_options.dart` (or
/// `--dart-define=FIREBASE_PROJECT_ID=...` is supplied), [initializeWatotoFirebase]
/// initializes Firebase and [createAuthService] returns [FirebaseAuthService].
///
/// Writes account docs to **accounts/{uid}** and consent records to
/// **accounts/{uid}/consents/{id}** (matching `backend/firestore.rules`).
library;

import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:cloud_functions/cloud_functions.dart';
import 'package:firebase_auth/firebase_auth.dart' as fb;

import '../../firebase/firebase_bootstrap.dart';
import '../../firebase_options.dart';
import 'auth_service.dart';

/// True when the binary was built with `--dart-define=USE_FIREBASE=true` or
/// when `DefaultFirebaseOptions.isConfigured` is true.
const useFirebase = bool.fromEnvironment('USE_FIREBASE', defaultValue: false);

/// True when `lib/firebase_options.dart` was generated by FlutterFire or passed
/// via `--dart-define`.
const firebaseOptionsConfigured = bool.fromEnvironment(
  'FIREBASE_OPTIONS_CONFIGURED',
  defaultValue: false,
);

/// Abstraction over the Firebase SDKs used by [FirebaseAuthService] so unit
/// tests can verify auth, account creation, and consent recording without
/// native platform channels.
abstract class FirebaseAuthBackend {
  AuthUser? get currentUser;
  Future<AuthUser> signInAnonymously();
  Future<AuthUser> createOrLinkParent({
    required String email,
    required String password,
    String? displayName,
  });
  Future<AuthUser> signInWithEmailAndPassword({
    required String email,
    required String password,
  });
  Future<void> signOut();
  Future<String?> getIdToken({bool forceRefresh = false});
  Future<void> sendPasswordResetEmail(String email);
  Future<void> confirmPasswordReset({
    required String code,
    required String newPassword,
  });
  Future<void> upsertAccountDoc({
    required String uid,
    required Map<String, Object?> data,
  });
  Future<void> recordConsent({
    required String uid,
    required String policyVersion,
    required String method,
  });
  Future<void> requestAccountDeletion();
  Future<Map<String, dynamic>> exportAccountData();
}

/// Default SDK-backed [FirebaseAuthBackend] using `firebase_auth`,
/// `cloud_firestore`, and `cloud_functions`.
class SdkFirebaseAuthBackend implements FirebaseAuthBackend {
  SdkFirebaseAuthBackend({
    fb.FirebaseAuth? auth,
    FirebaseFirestore? firestore,
    FirebaseFunctions? functions,
  }) {
    _auth = auth;
    _firestore = firestore;
    _functions = functions;
  }

  late final fb.FirebaseAuth? _auth;
  late final FirebaseFirestore? _firestore;
  late final FirebaseFunctions? _functions;

  fb.FirebaseAuth get _fbAuth => _auth ?? fb.FirebaseAuth.instance;
  FirebaseFirestore get _db => _firestore ?? FirebaseFirestore.instance;
  FirebaseFunctions get _fn => _functions ?? FirebaseFunctions.instance;

  static AuthUser _mapUser(fb.User u) =>
      AuthUser(uid: u.uid, email: u.email, isAnonymous: u.isAnonymous);

  @override
  AuthUser? get currentUser {
    final u = _fbAuth.currentUser;
    return u == null ? null : _mapUser(u);
  }

  @override
  Future<AuthUser> signInAnonymously() async {
    final existing = _fbAuth.currentUser;
    if (existing != null) return _mapUser(existing);
    final cred = await _fbAuth.signInAnonymously();
    final user = cred.user;
    if (user == null) {
      throw StateError('Firebase anonymous sign-in returned no user.');
    }
    return _mapUser(user);
  }

  @override
  Future<AuthUser> createOrLinkParent({
    required String email,
    required String password,
    String? displayName,
  }) async {
    final current = _fbAuth.currentUser;
    fb.UserCredential cred;
    if (current != null && current.isAnonymous) {
      final emailCred = fb.EmailAuthProvider.credential(
        email: email,
        password: password,
      );
      cred = await current.linkWithCredential(emailCred);
    } else {
      cred = await _fbAuth.createUserWithEmailAndPassword(
        email: email,
        password: password,
      );
    }
    final user = cred.user;
    if (user == null) {
      throw StateError('Firebase parent sign-up returned no user.');
    }
    if (displayName != null && displayName.trim().isNotEmpty) {
      await user.updateDisplayName(displayName.trim());
    }
    try {
      await user.sendEmailVerification();
    } catch (_) {
      // Verification email is best-effort and must not block account creation.
    }
    return _mapUser(user);
  }

  @override
  Future<AuthUser> signInWithEmailAndPassword({
    required String email,
    required String password,
  }) async {
    final cred = await _fbAuth.signInWithEmailAndPassword(
      email: email,
      password: password,
    );
    final user = cred.user;
    if (user == null) {
      throw StateError('Firebase sign-in returned no user.');
    }
    return _mapUser(user);
  }

  @override
  Future<void> signOut() => _fbAuth.signOut();

  @override
  Future<String?> getIdToken({bool forceRefresh = false}) async {
    return _fbAuth.currentUser?.getIdToken(forceRefresh);
  }

  @override
  Future<void> sendPasswordResetEmail(String email) {
    return _fbAuth.sendPasswordResetEmail(email: email);
  }

  @override
  Future<void> confirmPasswordReset({
    required String code,
    required String newPassword,
  }) {
    return _fbAuth.confirmPasswordReset(code: code, newPassword: newPassword);
  }

  @override
  Future<void> upsertAccountDoc({
    required String uid,
    required Map<String, Object?> data,
  }) async {
    await _db.collection('accounts').doc(uid).set(
      {
        ...data,
        'createdAt': FieldValue.serverTimestamp(),
        'updatedAt': FieldValue.serverTimestamp(),
      },
      SetOptions(merge: true),
    );
  }

  @override
  Future<void> recordConsent({
    required String uid,
    required String policyVersion,
    required String method,
  }) async {
    try {
      await _fn.httpsCallable('recordConsent').call<dynamic>(<String, Object?>{
        'method': method,
        'scope': 'account',
      });
    } catch (_) {
      // Fallback to direct write allowed by `match /consents/{consentId}` in
      // backend/firestore.rules (`allow create: if isOwner(uid) && ...`).
      await _db.collection('accounts').doc(uid).collection('consents').add({
        'policyVersion': policyVersion,
        'method': method,
        'scope': 'account',
        'createdAt': FieldValue.serverTimestamp(),
      });
    }
  }

  @override
  Future<void> requestAccountDeletion() async {
    await _fn.httpsCallable('requestAccountDeletion').call<dynamic>();
  }

  @override
  Future<Map<String, dynamic>> exportAccountData() async {
    final res = await _fn.httpsCallable('exportAccountData').call<dynamic>();
    final data = res.data;
    if (data is Map) {
      return Map<String, dynamic>.from(data);
    }
    return <String, dynamic>{};
  }
}

/// Production Firebase adapter implementing [AuthService].
///
/// Writes account docs to `accounts/{uid}` while strictly omitting server-owned
/// fields (`plan`, `entitlementExpiry`, `deletedAt`) per `backend/firestore.rules`.
class FirebaseAuthService implements AuthService {
  FirebaseAuthService({FirebaseAuthBackend? backend})
    : _backend = backend ?? SdkFirebaseAuthBackend();

  final FirebaseAuthBackend _backend;

  static const _setup =
      'Firebase is not initialized. Run `flutterfire configure` (or pass '
      '--dart-define=FIREBASE_PROJECT_ID=...) so DefaultFirebaseOptions '
      'is configured. See apps/mobile/tool/setup_firebase.md';

  void _requireReady() {
    if (!isFirebaseInitialized) {
      throw StateError(_setup);
    }
  }

  /// Sanitizes an account payload so client writes never touch server-owned
  /// fields forbidden by `backend/firestore.rules`.
  static Map<String, Object?> buildClientAccountPayload({
    required String email,
    required String consentVersion,
    String? displayName,
  }) {
    return <String, Object?>{
      'email': email.trim(),
      'consentVersion': consentVersion,
      if (displayName != null && displayName.trim().isNotEmpty)
        'displayName': displayName.trim(),
    };
  }

  @override
  AuthUser? get current {
    if (!isFirebaseInitialized) return null;
    try {
      return _backend.currentUser;
    } catch (_) {
      return null;
    }
  }

  @override
  Future<AuthUser> ensureAnonymousSession() async {
    _requireReady();
    return _backend.signInAnonymously();
  }

  @override
  Future<AuthUser> signUpParent({
    required String email,
    required String password,
    required bool consent,
    String? displayName,
  }) async {
    if (!consent) {
      throw StateError('Parental consent is required to create an account.');
    }
    _requireReady();
    final trimmedEmail = email.trim();
    final user = await _backend.createOrLinkParent(
      email: trimmedEmail,
      password: password,
      displayName: displayName,
    );
    final payload = buildClientAccountPayload(
      email: trimmedEmail,
      consentVersion: consentPolicyVersion,
      displayName: displayName,
    );
    await _backend.upsertAccountDoc(uid: user.uid, data: payload);
    await _backend.recordConsent(
      uid: user.uid,
      policyVersion: consentPolicyVersion,
      method: 'signup-checkbox',
    );
    return user;
  }

  @override
  Future<AuthUser> signInParent({
    required String email,
    required String password,
  }) async {
    _requireReady();
    return _backend.signInWithEmailAndPassword(
      email: email.trim(),
      password: password,
    );
  }

  @override
  Future<void> signOut() async {
    if (!isFirebaseInitialized) return;
    await _backend.signOut();
  }

  @override
  Future<String?> getIdToken({bool forceRefresh = false}) async {
    if (!isFirebaseInitialized) return null;
    return _backend.getIdToken(forceRefresh: forceRefresh);
  }

  @override
  Future<void> sendPasswordResetEmail(String email) async {
    _requireReady();
    await _backend.sendPasswordResetEmail(email.trim());
  }

  @override
  Future<void> confirmPasswordReset({
    required String code,
    required String newPassword,
  }) async {
    _requireReady();
    await _backend.confirmPasswordReset(
      code: code.trim(),
      newPassword: newPassword,
    );
  }

  /// Schedules soft deletion + 30-day purge via the `requestAccountDeletion`
  /// Cloud Function (`backend/functions/src/index.ts`).
  Future<void> requestAccountDeletion() async {
    _requireReady();
    await _backend.requestAccountDeletion();
  }

  /// Exports all account, profile, progress, and consent records via the
  /// `exportAccountData` Cloud Function (`backend/functions/src/index.ts`).
  Future<Map<String, dynamic>> exportAccountData() async {
    _requireReady();
    return _backend.exportAccountData();
  }
}

/// Picks [FirebaseAuthService] when Firebase has been initialized, otherwise
/// offline [LocalAuthService].
AuthService createAuthService() {
  if (isFirebaseInitialized) {
    return FirebaseAuthService();
  }
  return LocalAuthService();
}

/// Whether cloud auth is configured for this build.
bool get isCloudAuthBuild =>
    (useFirebase && firebaseOptionsConfigured) ||
    DefaultFirebaseOptions.isConfigured;
