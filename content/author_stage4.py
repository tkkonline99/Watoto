"""Author stage 4 (ages 3–4) to full depth, in EN/SW/FR.

First stage outside the foundation band, and the first at the
`encourage-effort` tier — "Ages 3–5: friendly narrator rewards effort, never
time pressure". That changes the shape of a lesson twice over.

The depth floor rises from 4 steps to 6, because a three-year-old can hold a
sequence a one-year-old cannot. And the arc stops being parent-led: stages 1–3
closed by sending the pair off the glass to find a real cup or clap real hands,
because at that age the parent *is* the user. Here the child is the user, and
the arc is

    hook → do it → do it again → a harder one → use it somewhere else → close

with the close naming the effort rather than the result, which is what the
stage's own focus line asks for ("Reward effort").

**No recap questions**, deliberately. Every stage-4 item carries
`reading: false`, and a recap is a written multiple choice. Stage 5 — same
tier, same author, but `reading: true` — has all thirty of its recaps already,
and that is the line the library drew. It is worth revisiting later: the recap
view narrates as well as prints, so a two-option spoken recap could work here.
Adding one would be a curriculum decision, not a formatting one.

    python content/author_stage4.py            # from the repo root
    python content/author_stage4.py --check    # verify only, exit 1 on drift
"""
