def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="verify the library already carries this stage")
    args = ap.parse_args()
    overlap = PILOT_IDS & EXTRA_STEPS.keys()
    if overlap:
        print("refusing to run: these are pilot lessons and would be truncated:")
        for lid in sorted(overlap):
            print("  x " + lid)
        return 1
    return apply_stage(
        stage=STAGE,
        ages=AGES,
        tier=TIER,
        base_step_counts=BASE_STEP_COUNTS,
        extra_steps=EXTRA_STEPS,
        new_quizzes=NEW_QUIZZES,
        new_stories=NEW_STORIES,
        min_steps=MIN_STEPS,
        min_questions=MIN_QUESTIONS,
        min_pages=MIN_PAGES,
        reading=True,
        check_only=args.check,
    )


if __name__ == "__main__":
    sys.exit(main())
