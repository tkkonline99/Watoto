"""Author stage 6 (ages 5–6) to full depth, in EN/SW/FR.

First `gamify-gently` stage, and the first stage authored against depth
minimums for all three item types rather than for lessons alone. Stages 1–5
were called done on lesson depth; their quizzes stayed at one question and
their stories at three pages, because nothing measured those. This script
fixes stage 6 on all three axes at once and
`apps/mobile/test/lesson_depth_test.dart` now holds every axis.

**The 8-step arc.** `gamify-gently` is 8 steps, two more than stage 4–5's
`encourage-effort` six, and the extra pair buys the two things a six-year-old
can do that a four-year-old cannot: follow a worked example, and check their
own answer. So the shape is

    0  hook                 (shipped)
    1  do it                (shipped)
    2  do it again, changed
    3  worked example       — the narrator thinks out loud
    4  a harder one
    5  use it somewhere else
    6  check yourself       — the child answers back
    7  close, naming the skill

Steps 0–1 already shipped for all thirty lessons, so this script appends six
(five for `s06.science.lesson.01`, which shipped with three).

**Quizzes go to four questions, stories to six pages.** One question cannot
tell a lucky tap from knowing it, and the adaptive resolver reads that single
result to decide what to offer next. Three pages is setup and stop.

**No bare `multiChoice` in appended steps** — same rule as stages 4 and 5. That
mechanic needs authored options and `apply_stage` cannot carry them, so a bare
one renders nothing to choose between. Questions are staged as taps instead.

**`numberAnswer` steps carry their answer explicitly** (the optional 5th
element). `planStep` will otherwise dig a number out of the English feedback,
which is the mechanic-inference trap in a new costume: the numeral can move or
vanish in translation and the Swahili child gets a box with no right answer.

    python content/author_stage6.py            # from the repo root
    python content/author_stage6.py --check    # verify only, exit 1 on drift
"""
