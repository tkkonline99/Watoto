"""Author stage 8 (ages 7–8) to full depth, in EN/SW/FR.

Why this exists
---------------
Stage 8 is the first stage the build has never shipped. `maxPublishedStage`
held it back for one reason, recorded in docs/V1_SCOPE.md: its 36 lessons are
two steps deep, which is not worth an eight-year-old's time. Breadth was real
and depth was not — 18 of the 24 quizzes the build plan asks for, one question
each; 6 of the 12 stories, three pages each.

What "full depth" means here is the `grant-autonomy` row of the depth tables:
8 steps per lesson, 4 questions per quiz, 6 pages per story. The tier name is
the design brief. A seven-year-old reads, works alone, and can be wrong without
a grown-up rescuing them, so the arc each lesson grows into is:

    state the rule → work one → try one → check yourself → apply it → carry it out

The two middle steps are the ones stage 8 had nowhere to put. "Check yourself"
matters most at this age and is the step the younger bands cannot use at all:
it hands the child the common mistake and asks them to spot it, rather than
telling them they were right.

Mechanics
---------
`multiChoice` is deliberately absent from EXTRA_STEPS. It needs authored
options and `apply_stage` has no way to carry them, so a bare multiChoice
renders nothing to choose between — the same note stages 4 and 5 carry. Steps
here use `tap`, `drag`, `explain`, `celebrate` and `numberAnswer`; the last one
always with its answer authored as the tuple's 5th element, never left for
`planStep` to dig out of English feedback.

Everything is written in all three languages, English included, because
`LocalizedItem._t` prefers the i18n overlay over the text in the library.

Idempotent: re-running replaces the same items and keys.

    python content/author_stage8.py            # from the repo root
    python content/author_stage8.py --check    # verify only, exit 1 on drift
"""
